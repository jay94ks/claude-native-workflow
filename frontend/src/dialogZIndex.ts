// 모달형 오버레이들이 "마지막에 연 것이 항상 위로" 오도록 공유하는
// z-index 카운터. 문서 다이얼로그↔칸반 카드 다이얼로그처럼 서로를
// 열 수 있는(양방향 참조) 오버레이 쌍은 고정 z-index만으로는 항상
// 올바르게 쌓이지 않는다 - 두 오버레이가 같은 고정값이면 어느 게
// 위로 오는지는 DOM 마운트 순서로 결정돼, 논리적으로 나중에 연
// 다이얼로그가 오히려 먼저 마운트된 다이얼로그 밑에 깔릴 수 있다.
// 대신 오버레이가 열릴 때마다 이 카운터에서 새 값을 받아 인라인
// style로 적용하면, 몇 단계로 중첩되든 항상 마지막에 연 것이 최상단에
// 온다.
const BASE_Z_INDEX = 1000;
let counter = 0;

export function nextDialogZIndex(): number {
  counter += 1;
  return BASE_Z_INDEX + counter;
}
